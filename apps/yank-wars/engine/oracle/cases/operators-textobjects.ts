// Operators (change.txt: d c y p P x X s S C D Y r J gJ ~ g~ gu gU g? > <) and text objects (motion.txt 6).
// Positions use N| and NG so a case starts exactly where the edge case is.
// lsel-allow: a list of oracle cases, one per entry

import { defineCases, type OracleCase, type OracleSettings } from "../types.ts";

type S = Partial<OracleSettings>;

// vim opens a file on line 1's first non-blank, the engine at 1:1 (see ot-start-cursor-*); 0 pins it.
function c(id: string, start: string, keys: string, settings?: S, note?: string): OracleCase {
  const pin = /^[ \t]/.test(start) && !/^\d+\|/.test(keys);
  return {
    id: `ot-${id}`,
    start,
    keys: pin ? `0${keys}` : keys,
    ...(settings === undefined ? {} : { settings }),
    ...(note === undefined ? {} : { note }),
  };
}

function each(id: string, start: string, keys: readonly string[], settings?: S): OracleCase[] {
  return keys.map((k, i) => c(`${id}-${i + 1}`, start, k, settings));
}

const SLUG: Readonly<Record<string, string>> = {
  "(": "paren",
  ")": "rparen",
  "[": "brack",
  "]": "rbrack",
  "{": "brace",
  "}": "rbrace",
  "<lt>": "lt",
  ">": "gt",
  '"': "dq",
  "'": "sq",
  "`": "bt",
};

function slug(obj: string): string {
  const m = /^(\d*)([ia])(.+)$/.exec(obj);
  if (!m) throw new Error(obj);
  return `${m[1]}${m[2]}${SLUG[m[3] as string] ?? m[3]}`;
}

// d, c (typing X) and y-then-P on each text object from each position.
function objects(id: string, start: string, positions: readonly string[], objs: readonly string[]) {
  const out: OracleCase[] = [];
  for (const obj of objs) {
    for (const [pi, pos] of positions.entries()) {
      const base = `${id}-${slug(obj)}-p${pi + 1}`;
      out.push(c(`${base}-d`, start, `${pos}d${obj}`));
      out.push(c(`${base}-c`, start, `${pos}c${obj}X<Esc>`));
      out.push(c(`${base}-y`, start, `${pos}y${obj}P`));
    }
  }
  return out;
}

